import {
  canTrackProcess,
  isProcessOwnedBySessionDepartment,
  matchesOperationalScope,
  type ProcessRecord,
  type SessionUser,
} from "@/lib/platform";

const INSTITUTIONAL_ROLES = new Set<string>([
  "master_admin",
  "master_ops",
  "prefeitura_admin",
  "prefeitura_supervisor",
  "analista",
  "financeiro",
  "setor_intersetorial",
  "fiscal",
  // Legacy role codes still authorized explicitly by the database.
  "admin_master",
  "admin_municipality",
  "admin_prefeitura",
  "analyst",
  "financial",
  "counter_service",
  "topography",
  "expedient",
]);

/**
 * Only an active, explicitly recognized internal account can read the
 * institutional history. New roles are deny-by-default until authorized.
 * External professionals and property owners use their own history routes.
 */
export function canReadInstitutionalHistory(
  session: Pick<SessionUser, "role" | "accountStatus">,
): boolean {
  return session.accountStatus === "active" && INSTITUTIONAL_ROLES.has(session.role);
}

/**
 * The read-only archive follows a municipality, NOT the current work queue:
 * an approved/forwarded process remains available for institutional audit.
 */
export function getInstitutionalHistoryProcesses(
  session: SessionUser,
  municipalityId: string | null | undefined,
  processes: readonly ProcessRecord[],
): ProcessRecord[] {
  if (!municipalityId || !canReadInstitutionalHistory(session)) return [];
  return processes.filter(
    (process) =>
      matchesOperationalScope(municipalityId, process) &&
      canTrackProcess(session, process, municipalityId),
  );
}

/** Visible records do not confer permission to send/receive or change them. */
export function canOperateInstitutionalHistoryProcess(
  session: SessionUser,
  process: ProcessRecord,
  municipalityId: string | null | undefined,
): boolean {
  if (
    !municipalityId ||
    !canReadInstitutionalHistory(session) ||
    session.role === "prefeitura_admin" ||
    !matchesOperationalScope(municipalityId, process) ||
    ["deferido", "indeferido", "arquivado"].includes(process.status)
  ) {
    return false;
  }
  return isProcessOwnedBySessionDepartment(session, process);
}

/** ISO and Brazilian local date/times generated by the platform. */
export function historicTimestamp(value?: string | null): number {
  const raw = String(value ?? "").trim();
  if (!raw) return 0;
  const br = raw.match(/^(\d{2})\/(\d{2})\/(\d{4})(?:[,\s]+(\d{2}):(\d{2})(?::(\d{2}))?)?/);
  if (br) {
    const [, dd, mm, yyyy, hh = "00", min = "00", ss = "00"] = br;
    const date = new Date(Number(yyyy), Number(mm) - 1, Number(dd), Number(hh), Number(min), Number(ss));
    if (date.getFullYear() !== Number(yyyy) || date.getMonth() !== Number(mm) - 1 || date.getDate() !== Number(dd)) return 0;
    return date.getTime();
  }
  const parsed = Date.parse(raw);
  return Number.isFinite(parsed) ? parsed : 0;
}
